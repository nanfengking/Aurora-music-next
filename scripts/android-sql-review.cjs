// Execute SQL extracted from the Android source against an isolated, in-memory host SQLite.
// This supplements, but never replaces, Android SQLite/instrumentation tests.
const { DatabaseSync } = require('node:sqlite')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const assert = require('node:assert/strict')
const source = readFileSync(join(__dirname, '../android/app/src/main/java/com/aurora/musicnext/MusicStore.java'), 'utf8')
const db = new DatabaseSync(':memory:')
const method = (signature) => {
  const start = source.indexOf(signature)
  assert.ok(start >= 0, signature)
  return source.slice(start, source.indexOf('\n    }', start))
}
const literal = (raw) => JSON.parse('"' + raw + '"')
const sql = (body, prefix) => {
  const result = [...body.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map(match => literal(match[1])).find(value => value.startsWith(prefix))
  assert.ok(result, prefix); return result
}
const executeSchema = (signature) => {
  for (const match of method(signature).matchAll(/db\.execSQL\("((?:[^"\\]|\\.)*)"\)/g)) db.exec(literal(match[1]))
}
try {
  executeSchema('public void onCreate(SQLiteDatabase db)')
  for (const name of ['Two', 'Three', 'Four']) executeSchema('private static void upgradeTo' + name + '(SQLiteDatabase db)')
  db.prepare("INSERT INTO songs(id,title,format,url,size,created_at,favorite,play_count) VALUES(?,?,?,?,?,'fixture',1,8)").run('fixture', 'Fixture song', 'm4a', 'https://example.com/music.m4a', 5000)
  db.exec("INSERT INTO history(song_id,action,timestamp) VALUES('fixture','start',12345); INSERT INTO playback_queue VALUES(1,'fixture'); INSERT INTO playback_state VALUES(1,'fixture',4567)")
  for (const name of ['Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten']) executeSchema('private static void upgradeTo' + name + '(SQLiteDatabase db)')
  const saved = db.prepare("SELECT favorite,play_count,last_played_at,download_token FROM songs WHERE id='fixture'").get()
  assert.equal(saved.favorite, 1); assert.equal(saved.play_count, 8); assert.equal(saved.last_played_at, 12345); assert.equal(saved.download_token, '')
  assert.equal(db.prepare('SELECT original_position FROM playback_queue').get().original_position, 1)
  const restored = db.prepare(sql(method('String[] savedPlayback()'), 'SELECT song_id,position_ms FROM playback_state'))
  assert.equal(restored.get(0).position_ms, 4567, 'Schema v8 retains the existing recovery point')
  const checkpoint = db.prepare(sql(method('void savePlayback(String id, long position, long revision)'), 'INSERT OR REPLACE INTO playback_state'))
  const forget = db.prepare('DELETE FROM playback_state WHERE restore_revision<?')
  assert.ok(method('void forgetPlayback(long disabledRevision)').includes('"restore_revision<?"'))
  forget.run(1); assert.equal(restored.get(0), undefined)
  checkpoint.run('fixture', 67890, 2); forget.run(1)
  assert.equal(restored.get(2).position_ms, 67890, 'Late clearing cannot erase a newer enabled resume point')
  assert.equal(restored.get(0), undefined, 'An old revision cannot recover a newer session')
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM playback_queue').get().n, 1)
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM history').get().n, 1)
  assert.equal(db.prepare('SELECT replay_gain_db,replay_peak FROM songs').get().replay_gain_db, null, 'Missing ReplayGain must not become a fabricated 0 dB')
  assert.equal(db.prepare('SELECT replay_gain_db,replay_peak FROM songs').get().replay_peak, null)
  db.exec('UPDATE songs SET replay_gain_db=-6.25,replay_peak=1.2345')
  assert.equal(db.prepare('SELECT replay_gain_db,replay_peak FROM songs').get().replay_gain_db, -6.25)
  assert.equal(db.prepare('SELECT replay_gain_db,replay_peak FROM songs').get().replay_peak, 1.2345)
  db.exec("UPDATE songs SET download_token='old',download_state='running'")
  const progress = db.prepare(sql(method('void downloadProgress(String id, String token, long received, long total, long priorBytes)'), 'UPDATE songs SET download_failures='))
  const active = db.prepare(sql(method('boolean downloadActive(String id, String token)'), 'SELECT 1 FROM songs'))
  const reserve = db.prepare(sql(method('long pendingBytes(String exceptId)'), 'SELECT COALESCE(SUM('))
  progress.run(2000, 0, 2000, 5000, 'fixture', 'old'); assert.equal(Object.values(reserve.get('other'))[0], 3000)
  db.exec('UPDATE songs SET download_failures=1')
  progress.run(0, 2000, 0, 5000, 'fixture', 'old'); progress.run(2000, 2000, 2000, 5000, 'fixture', 'old')
  assert.equal(db.prepare('SELECT download_failures FROM songs').get().download_failures, 1, 'Re-fetching the same bytes cannot reset failure budget')
  progress.run(2500, 2000, 2500, 5000, 'fixture', 'old'); assert.equal(db.prepare('SELECT download_failures FROM songs').get().download_failures, 0)
  db.exec("UPDATE songs SET download_state='paused'"); assert.equal(active.get('fixture', 'old'), undefined); assert.equal(Object.values(reserve.get('other'))[0], 0)
  db.exec("UPDATE songs SET download_token='new',download_state='pending'"); progress.run(4000, 0, 4000, 5000, 'fixture', 'old')
  assert.equal(db.prepare('SELECT download_bytes FROM songs').get().download_bytes, 2500, 'Stale worker cannot alter new-generation progress')
  assert.ok(active.get('fixture', 'new')); db.exec('UPDATE songs SET download_complete=1'); assert.equal(active.get('fixture', 'new'), undefined)
  assert.equal(db.prepare('SELECT cover_manual,background_path FROM songs').get().cover_manual, 0)
  assert.equal(db.prepare('SELECT cover_manual,background_path FROM songs').get().background_path, null)
  const guard = sql(method('void metadata('), 'id=? AND cover_manual=0')
  assert.equal(guard, 'id=? AND cover_manual=0')
  db.exec("UPDATE songs SET cover_path='chosen',cover_manual=1,lyrics='manual lyrics',background_path='chosen-background'")
  db.prepare('UPDATE songs SET cover_path=? WHERE ' + guard).run('embedded', 'fixture')
  assert.equal(db.prepare('SELECT cover_path FROM songs').get().cover_path, 'chosen')
  const lyricGuard = sql(method('void assets('), "id=? AND (lyrics IS NULL OR lyrics='')")
  db.prepare('UPDATE songs SET lyrics=? WHERE ' + lyricGuard).run('automatic lyrics', 'fixture')
  assert.equal(db.prepare('SELECT lyrics FROM songs').get().lyrics, 'manual lyrics')
  db.exec('UPDATE songs SET assets_checked_at=12345')
  db.exec(sql(method('void invalidateAssets()'), 'UPDATE songs SET assets_checked_at='))
  assert.equal(db.prepare('SELECT assets_checked_at FROM songs').get().assets_checked_at, 0)
  assert.equal(db.prepare('SELECT background_path FROM songs').get().background_path, 'chosen-background')
  console.log('ANDROID_SQL_PASS: extracted schema v1–10, nullable ReplayGain, manual-resource guards, recovery revisions with queue/history retention, reservations, pauses, retry budget and stale/completed generation guards. Host SQLite only; Android instrumentation still required.')
} finally { db.close() }
